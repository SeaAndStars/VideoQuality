#!/usr/bin/env python3
"""Builds VideoQuality.Tests/Fixtures/fonts/VQTestCff.otf: a tiny CFF-outline font (box glyphs
for printable ASCII) used to test subsetting of PostScript-flavoured OpenType fonts.

Needs fontTools (pip install fonttools). The output is our own work, released under CC0.
"""
import sys
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.t2CharStringPen import T2CharStringPen

out = sys.argv[1] if len(sys.argv) > 1 else "VideoQuality.Tests/Fixtures/fonts/VQTestCff.otf"
chars = [chr(c) for c in range(0x21, 0x7F)]
names = [".notdef", "space"] + [f"uni{ord(c):04X}" for c in chars]

fb = FontBuilder(1000, isTTF=False)
fb.setupGlyphOrder(names)
fb.setupCharacterMap({0x20: "space", **{ord(c): f"uni{ord(c):04X}" for c in chars}})

def box(width):
    pen = T2CharStringPen(width, None)
    if width:
        pen.moveTo((50, 0)); pen.lineTo((width - 50, 0)); pen.lineTo((width - 50, 700)); pen.lineTo((50, 700)); pen.closePath()
    return pen.getCharString()

charstrings = {name: box(0 if name == "space" else 600) for name in names}
fb.setupCFF("VQTestCff-Regular", {"FullName": "VQ Test CFF"}, charstrings, {})
fb.setupHorizontalMetrics({name: (600, 50) for name in names})
fb.setupHorizontalHeader(ascent=800, descent=-200)
fb.setupNameTable({"familyName": "VQ Test CFF", "styleName": "Regular", "psName": "VQTestCff-Regular",
                   "copyright": "CC0 test font generated by scripts/make-test-cff-font.py"})
fb.setupOS2(sTypoAscender=800, sTypoDescender=-200, usWinAscent=800, usWinDescent=200, usWeightClass=400)
fb.setupPost()
fb.font["head"].created = fb.font["head"].modified = 3_000_000_000  # reproducible
fb.save(out)
